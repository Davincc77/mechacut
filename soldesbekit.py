def soldes_be(year, territory=None, season=None, as_of=None):
    try:
        year = int(year)
    except (TypeError, ValueError):
        raise SoldesBeError("year", "not an integer year: %r" % (year,),
                            "expected integer >= 2014")
    if year > 9999:
        raise SoldesBeError("year", "not an ISO-representable year: %d"
                            % year, "year <= 9999")
    _territory(territory)
