def _fold(s):
    out = []
    for ch in str(s).lower():
        if ch in "àâä":
            ch = "a"
        elif ch in "éèêë":
            ch = "e"
        elif ch in "îï":
            ch = "i"
        elif ch in "ôö":
            ch = "o"
        elif ch in "ùûüç":
            ch = {"ù": "u", "û": "u", "ü": "u", "ç": "c"}[ch]
        elif ord(ch) > 127:
            ch = "?"
        out.append(ch)
    s = "".join(out)
    return " ".join(s.replace("-", " ").replace("/", " ").split())


def _iso(d):
    return d.isoformat()


def _parse_as_of(s):
    try:
        return _date.date.fromisoformat(str(s))
    except Exception:
        raise SoldesBeError("as_of", "not an ISO calendar date: %r" % (s,),
                            "expected 'YYYY-MM-DD'")


def _territory(raw):
    t = _fold(raw if raw is not None else "belgique")
    if t in _BEL or t.startswith("belg") or t in ("bruxelles", "brussel"):
        return
    for token, why in _REFUSE_NOMMES.items():
        if t == token or t.startswith(token):
            raise SoldesBeError(
                "territory",
                "%r refuse par nom portant son fait : %s ; la table ne "
                "rejoue QUE le Livre VI belge" % (raw, why),
                "un territoire belge (liste closee)")
    for token in _REFUSE_GEN:
        if token in t:
            raise SoldesBeError(
                "territory",
                "%r refuse par nom portant son fait : calendrier etranger "
                "non rejoue — la table ne dit AUCUNE date hors Livre VI "
                "belge" % (raw,),
                "un territoire belge (liste closee)")
    raise SoldesBeError("territory", "not in the closed table: %r"
                        % (raw,), "belgique (liste closee)")


def _season(raw):
    s = _fold(raw if raw is not None else "both")
    if s in _SEASONS:
        return _SEASONS[s]
    raise SoldesBeError(
        "season", "unknown season %r — attendu hiver|ete|both (liste "
        "closee)" % (raw,), "hiver | ete | both")


